const fs=require('fs'),path=require('path'),assert=require('node:assert/strict'),vm=require('node:vm'),ts=require('typescript');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(root+'/src/lib/lecture-player-document.ts','utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const context={exports:{}};vm.runInNewContext(compiled,context);
const {nativeLecturePlayerDocument,LECTURE_PLAYER_ORIGIN}=context.exports;
assert.equal(LECTURE_PLAYER_ORIGIN,'https://com.medonex.app');
const asset=fs.readFileSync(root+'/assets/lecture-video-player.html','utf8');
const html=nativeLecturePlayerDocument(asset,'abcd-1234');
assert(html.includes('window.__LECTURE_SCOPE__="abcd-1234"'));
assert(html.includes('<base href="https://com.medonex.app/">'));
assert(html.includes('window.__LECTURE_SCOPE__||new URLSearchParams'));
assert(html.includes('name="referrer" content="strict-origin-when-cross-origin"'));
assert.throws(()=>nativeLecturePlayerDocument(asset,'</script>'));
const frame=fs.readFileSync(root+'/src/components/lecture/LectureVideoPlayer.tsx','utf8');
assert(frame.includes('source={{ html, baseUrl: LECTURE_PLAYER_ORIGIN + "/" }}'));
assert(frame.includes('FileSystem.readAsStringAsync(asset.localUri)'));
assert(!frame.includes('source={{ uri }}'));
for(const setting of ['sharedCookiesEnabled={false}','thirdPartyCookiesEnabled={false}','allowFileAccess={false}','allowUniversalAccessFromFileURLs={false}','data?.scope !== scope']) assert(frame.includes(setting));
assert(!html.includes('authSessionV2'));
const build=fs.readFileSync(root+'/scripts/build-lecture-video-player.mjs','utf8');
assert(build.includes('window.__LECTURE_SCOPE__||new URLSearchParams'));
assert(build.includes('name="referrer" content="strict-origin-when-cross-origin"'));
console.log('PASS packaged HTML uses native HTTPS base URL, app identity, explicit referrer, pre-script scope injection, cookie/file-access isolation, and reproducible build template');
